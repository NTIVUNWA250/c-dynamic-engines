const char SAMPLE_PARAGRAPH[] =
    "Research findings pertaining to language education and distance education point to "
    "the lack of online reading materials written in African languages and reflecting "
    "African contexts. Such a shortage is a challenge to literacy skills development in "
    "Africa. In Rwanda, although there are some graded readers to support the teaching of "
    "reading in Kinyarwanda, there is a shortage of enjoyable storybooks on which "
    "children can practice their reading skills. This paper contributes to addressing "
    "this challenge by investigating the partnership between the University of "
    "Rwanda-College of Education and South African Institute of Distance Education's "
    "(Saide) African Storybook Initiative, which provides a website of digital storybooks "
    "in Kinyarwanda and other languages for early grade reading. Data were collected from "
    "32 Rwandan teacher educators who participated in a workshop. Participants created "
    "online picture storybooks in Kinyarwanda, translated some from other languages and "
    "published them on the African Storybook website. The researchers firstly observed "
    "their activities during the workshop, then, all participants filled in the "
    "questionnaire and ten teachers were interviewed on opportunities offered and "
    "challenges encountered during the translation process. The key finding is that "
    "teachers' experiences with translation revealed differences in story reading levels "
    "between the original Kinyarwanda folktales and English translated versions. They "
    "found special features of African agglutinating languages in determining reading "
    "levels, and foreignization of translated stories based on cultural clashes. "
    "Differences in length between the original and the translated stories were observed, "
    "as well as the specificity of English versions in reinforcing more critical thinking "
    "than the translated Kinyarwanda versions. The paper recommends teacher educators and "
    "translators to bear in mind that adaptation to African languages requires care and a "
    "high level of ability to maintain the meaning and moral lesson of the original tale "
    "and make it enjoyable for children. Translating and adapting stories from English "
    "into agglutinative African languages have implications for early grade reading "
    "interventions in African schools since children stories on African storybook website "
    "are available in more than 100 African languages.";
